// Generates board/slots.gen.ts: one import per `<feature>/board.tsx`.
// Gitignored and regenerated on every start, so a reverted feature simply drops out.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { Glob } from "bun";

const ROOT = path.resolve(import.meta.dir, "..");

export async function generateSlots(): Promise<string[]> {
  const files = (await Array.fromAsync(new Glob("*/board.tsx").scan({ cwd: ROOT })))
    .filter((f) => !f.startsWith("board/") && !f.startsWith("node_modules/") && !f.startsWith("vendor/"))
    .sort();
  const lines = [
    "// Generated by scripts/gen.ts. Do not edit.",
    'import type { BoardFeature } from "./slots.ts";',
    ...files.map((f, i) => `import f${i} from "../${f}";`),
    `export const features: BoardFeature[] = [${files.map((_, i) => `f${i}`).join(", ")}];`,
    "",
  ];
  // Written only when the features changed: every server start (and every test that starts one)
  // would otherwise rewrite a file in the repo while another may be bundling it.
  const file = path.join(ROOT, "board", "slots.gen.ts");
  const text = lines.join("\n");
  if (!existsSync(file) || readFileSync(file, "utf8") !== text) writeFileSync(file, text);
  return files;
}

if (import.meta.main) console.log(`slots: ${(await generateSlots()).join(", ") || "none"}`);
